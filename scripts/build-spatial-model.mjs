import {readFile,writeFile,copyFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {gzipSync} from 'node:zlib';
import {MeshoptEncoder} from 'meshoptimizer';
const root=new URL('../',import.meta.url);
const input=await readFile(new URL('dist/assets/model/second-floor.json',root));
const source=JSON.parse(input);
await MeshoptEncoder.ready;
const gltf={asset:{version:'2.0',generator:'Sound Atlas lossless mesh export'},extensionsUsed:['EXT_meshopt_compression'],extensionsRequired:['EXT_meshopt_compression'],scene:0,scenes:[{nodes:[]}],nodes:[],meshes:[],accessors:[],bufferViews:[],buffers:[],extras:{metadata:source.metadata,materialDefinitions:source.materials}};
const chunks=[];let offset=0,fallbackOffset=0;
function append(array,stride,mode){
 const encoded=MeshoptEncoder.encodeGltfBuffer(new Uint8Array(array.buffer,array.byteOffset,array.byteLength),array.byteLength/stride,stride,mode);
 const pad=(4-encoded.byteLength%4)%4;
 const view={buffer:1,byteOffset:fallbackOffset,byteLength:array.byteLength,extensions:{EXT_meshopt_compression:{buffer:0,byteOffset:offset,byteLength:encoded.byteLength,byteStride:stride,count:array.byteLength/stride,mode}}};
 chunks.push(Buffer.from(encoded),Buffer.alloc(pad));offset+=encoded.byteLength+pad;fallbackOffset+=array.byteLength;
 // All attributes are float32 and all view starts stay four-byte aligned.
 const fallbackPad=(4-fallbackOffset%4)%4;fallbackOffset+=fallbackPad;
 gltf.bufferViews.push(view);return gltf.bufferViews.length-1;
}
function accessor(values,size,type,indices=false){
 const maxIndex=indices?values.reduce((a,b)=>Math.max(a,b),0):0;
 const array=indices?(maxIndex<65536?new Uint16Array(values):new Uint32Array(values)):new Float32Array(values);
 const stride=indices?array.BYTES_PER_ELEMENT:size*4;
 const item={bufferView:append(array,stride,indices?'TRIANGLES':'ATTRIBUTES'),componentType:indices?(stride===2?5123:5125):5126,count:array.length/size,type};
 if(type==='VEC3'&&!indices){item.min=Array(size).fill(Infinity);item.max=Array(size).fill(-Infinity);for(let i=0;i<array.length;i++){item.min[i%size]=Math.min(item.min[i%size],array[i]);item.max[i%size]=Math.max(item.max[i%size],array[i]);}}
 gltf.accessors.push(item);return gltf.accessors.length-1;
}
for(const mesh of source.meshes){
 const vertexCount=mesh.positions.length/3;
 if(mesh.normals.length!==vertexCount*3||mesh.uvs.length!==vertexCount*2)throw new Error('Missing mesh attributes: '+mesh.name);
 const attributes={POSITION:accessor(mesh.positions,3,'VEC3'),NORMAL:accessor(mesh.normals,3,'VEC3'),TEXCOORD_0:accessor(mesh.uvs,2,'VEC2')};
 gltf.meshes.push({name:mesh.name,primitives:[{attributes,indices:accessor(mesh.indices,1,'SCALAR',true),mode:4}],extras:{materialId:mesh.material}});
 gltf.nodes.push({mesh:gltf.meshes.length-1,name:mesh.name,extras:{materialId:mesh.material}});gltf.scenes[0].nodes.push(gltf.nodes.length-1);
}
gltf.buffers=[{byteLength:offset},{byteLength:fallbackOffset,extensions:{EXT_meshopt_compression:{fallback:true}}}];
const json=Buffer.from(JSON.stringify(gltf));const padded=Buffer.concat([json,Buffer.alloc((4-json.length%4)%4,32)]);const binary=Buffer.concat(chunks);
const header=Buffer.alloc(12);header.writeUInt32LE(0x46546c67,0);header.writeUInt32LE(2,4);header.writeUInt32LE(12+8+padded.length+8+binary.length,8);
const jsonHeader=Buffer.alloc(8);jsonHeader.writeUInt32LE(padded.length,0);jsonHeader.writeUInt32LE(0x4e4f534a,4);
const binHeader=Buffer.alloc(8);binHeader.writeUInt32LE(binary.length,0);binHeader.writeUInt32LE(0x004e4942,4);
const output=Buffer.concat([header,jsonHeader,padded,binHeader,binary]);
const hash=createHash('sha256').update(output).digest('hex').slice(0,12);
const filename=`second-floor.${hash}.glb`;
await writeFile(new URL('dist/assets/model/'+filename,root),output);
await writeFile(new URL('dist/assets/model/'+filename+'.gz',root),gzipSync(output,{level:9}));
await writeFile(new URL('dist/model-asset.js',root),`// Generated by scripts/build-spatial-model.mjs.\nexport const MODEL_ASSET = './assets/model/${filename}';\nexport const COMPRESSED_MODEL_ASSET = './assets/model/${filename}.gz';\n`);
for(const file of ['loaders/GLTFLoader.js','utils/BufferGeometryUtils.js','utils/SkeletonUtils.js']){
 await mkdir(new URL('dist/assets/vendor/'+file.split('/')[0]+'/',root),{recursive:true});
 await copyFile(new URL('node_modules/three/examples/jsm/'+file,root),new URL('dist/assets/vendor/'+file,root));
}
await copyFile(new URL('node_modules/meshoptimizer/meshopt_decoder.mjs',root),new URL('dist/assets/vendor/meshopt_decoder.mjs',root));
await copyFile(new URL('node_modules/meshoptimizer/LICENSE.md',root),new URL('dist/assets/vendor/meshoptimizer-LICENSE.md',root));
await mkdir(new URL('.vercel/',root),{recursive:true});
const report={file:filename,jsonBytes:input.length,glbBytes:output.length,jsonGzipBytes:gzipSync(input).length,glbGzipBytes:gzipSync(output).length,meshes:source.meshes.length,vertices:source.meshes.reduce((n,m)=>n+m.positions.length/3,0),triangles:source.meshes.reduce((n,m)=>n+m.indices.length/3,0)};
await writeFile(new URL('.vercel/model-build-report.json',root),JSON.stringify(report,null,2));console.log(report);
